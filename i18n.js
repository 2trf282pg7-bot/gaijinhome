function getConcieregeResult(visa, budget, area, guarantor) {
  if (visa === 'tourist') return conciergeResults.tourist_short;
  if (visa === 'wh' && guarantor === 'no') return conciergeResults.wh_no_guarantor;
  if (visa === 'pr' || visa === 'spouse') return conciergeResults.pr_spouse;
  if (visa === 'student' && guarantor === 'no') return conciergeResults.student_no_guarantor;
  if (area === 'osaka' && (budget === 'under60' || budget === '60-100')) return conciergeResults.osaka_budget;
  if (guarantor === 'yes') return conciergeResults.work_with_guarantor;
  return conciergeResults.work_no_guarantor;
}

document.addEventListener('DOMContentLoaded', () => {
  const saved = localStorage.getItem('gh-lang');
  const browser = navigator.language.split('-')[0];
  const supported = Object.keys(translations);
  const initial = saved || (supported.includes(browser) ? browser : 'en');
  setLanguage(initial);
});
